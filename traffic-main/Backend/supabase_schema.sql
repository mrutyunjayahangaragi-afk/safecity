-- Backward-compat view so old code hitting user_profiles still works
-- Drop the old TABLE first (from schema v1) so we can create the view in its place
drop view if exists public.user_profiles cascade;
drop table if exists public.user_profiles cascade;
create or replace view public.user_profiles as
  select
    id,
    user_id::text,
    full_name  as display_name,
    email,
    phone_number as phone,
    role,
    created_at
  from public.profiles;

-- ═══════════════════════════════════════════════════════════════════════════
-- MIGRATION GUARD: Drop v1 tables that conflict with v2 schema
-- (v1 used TEXT for user_id; v2 uses UUID referencing auth.users)
-- CASCADE removes dependent RLS policies so we can recreate them cleanly.
-- Data in these tables is intentionally not preserved because the old
-- TEXT user_ids are not valid UUIDs and cannot be migrated automatically.
-- ═══════════════════════════════════════════════════════════════════════════
do $$
begin
  -- Only drop if the existing user_id column is TEXT (v1 schema)
  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name   = 'route_history'
      and column_name  = 'user_id'
      and data_type    = 'text'
  ) then
    drop table if exists public.route_history cascade;
    raise notice 'Dropped v1 route_history (TEXT user_id)';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name   = 'sos_requests'
      and column_name  = 'user_id'
      and data_type    = 'text'
  ) then
    drop table if exists public.sos_requests cascade;
    raise notice 'Dropped v1 sos_requests (TEXT user_id)';
  end if;

  if exists (
    select 1 from information_schema.columns
    where table_schema = 'public'
      and table_name   = 'incident_reports'
      and column_name  = 'user_id'
      and data_type    = 'text'
  ) then
    drop table if exists public.incident_reports cascade;
    raise notice 'Dropped v1 incident_reports (TEXT user_id)';
  end if;
end;
$$;

