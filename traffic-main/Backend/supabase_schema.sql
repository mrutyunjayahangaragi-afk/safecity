-- TRIGGER: auto-update updated_at
-- ═══════════════════════════════════════════════════════════════════════════
create or replace function public.handle_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  tbl text;
begin
  foreach tbl in array array[
    'profiles','route_history','saved_routes','incident_reports',
    'traffic_reports','weather_reports','crowd_density_reports',
    'sos_requests','emergency_requests','notifications',
    'favorite_locations','recent_searches'
  ] loop
    execute format($f$
      drop trigger if exists set_updated_at on public.%I;
      create trigger set_updated_at
        before update on public.%I
        for each row execute function public.handle_updated_at();
    $f$, tbl, tbl);
  end loop;
end;
$$;

-- ═══════════════════════════════════════════════════════════════════════════
-- TRIGGER: auto-create profile on first sign-up (via auth.users insert)
-- ═══════════════════════════════════════════════════════════════════════════
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer as $$
declare
  _provider  text := coalesce(new.raw_app_meta_data->>'provider', 'email');
  _full_name text := coalesce(
    new.raw_user_meta_data->>'full_name',
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'display_name',
    split_part(coalesce(new.email, ''), '@', 1),
    'User'
  );
  _avatar    text := coalesce(
    new.raw_user_meta_data->>'avatar_url',
    new.raw_user_meta_data->>'picture',
    null
  );
begin
  insert into public.profiles (user_id, full_name, email, phone_number, avatar_url, provider, last_login)
  values (
    new.id,
    _full_name,
    new.email,
    new.phone,
    _avatar,
    _provider,
    now()
  )
  on conflict (user_id) do update set
    full_name  = excluded.full_name,
    avatar_url = coalesce(excluded.avatar_url, profiles.avatar_url),
    last_login = now(),
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Also update last_login on sign-in (update of last_sign_in_at)
create or replace function public.handle_user_login()
returns trigger language plpgsql security definer as $$
begin  
  if new.last_sign_in_at is distinct from old.last_sign_in_at then
    update public.profiles
      set last_login = now(), updated_at = now()
      where user_id = new.id;
  end if;
  return new;
end;
$$;

drop trigger if exists on_auth_user_login on auth.users;
create trigger on_auth_user_login
  after update on auth.users
  for each row execute function public.handle_user_login();


